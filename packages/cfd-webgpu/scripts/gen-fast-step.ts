/**
 * Writes src/fast-step.ts: the fluid-cell update of the reference solver
 * unrolled over the 19 directions of D3Q19, for cells whose 18 neighbours are
 * all inside the box and none is solid (the bulk of any tunnel). Same
 * arithmetic as the general path of ReferenceSolver.step; the tests run both.
 *
 *   node scripts/gen-fast-step.ts
 */
import { writeFileSync } from "node:fs";
import { CX, CY, CZ, Q, W } from "../src/lattice.ts";

const term = (coef: number, name: string): string =>
  coef === 0 ? "" : coef === 1 ? ` + ${name}` : coef === -1 ? ` - ${name}` : coef < 0 ? ` - ${-coef} * ${name}` : ` + ${coef} * ${name}`;
const sum = (parts: string): string => (parts.startsWith(" + ") ? parts.slice(3) : parts.startsWith(" - ") ? `-${parts.slice(3)}` : parts || "0");
const wname = (q: number): string => (q === 0 ? "W0" : q <= 6 ? "WA" : "WD");

const lines: string[] = [];
lines.push("// Generated by scripts/gen-fast-step.ts. Do not edit by hand.");
lines.push("/* eslint-disable */");
lines.push("const W0 = 1 / 3;");
lines.push("const WA = 1 / 18;");
lines.push("const WD = 1 / 36;");
lines.push("");
lines.push("/**");
lines.push(" * Pull, regularized BGK with Smagorinsky, for one interior fluid cell c.");
lines.push(" * off[q] = c_q · (1, nx, nx·ny): the pulled population comes from c − off[q].");
lines.push(" * Writes ρ, ux, uy, uz to macro[0..3].");
lines.push(" */");
lines.push("export function fastFluidStep(g: Float64Array, next: Float64Array, n: number, c: number, off: Int32Array, tau0: number, smag: number, macro: Float64Array): void {");
for (let q = 0; q < Q; q++) lines.push(q === 0 ? `  const g0 = g[c]!;` : `  const g${q} = g[${q} * n + c - off[${q}]!]!;`);
lines.push(`  const rho = 1 + ${Array.from({ length: Q }, (_, q) => `g${q}`).join(" + ")};`);
for (const [axis, C] of [["x", CX], ["y", CY], ["z", CZ]] as const) {
  let s = "";
  for (let q = 0; q < Q; q++) s += term(C[q]!, `g${q}`);
  lines.push(`  const j${axis} = ${sum(s)};`);
}
lines.push("  const ux = jx / rho, uy = jy / rho, uz = jz / rho;");
lines.push("  const uu = 1.5 * (ux * ux + uy * uy + uz * uz);");
for (let q = 0; q < Q; q++) {
  const cu = sum(term(CX[q]!, "ux") + term(CY[q]!, "uy") + term(CZ[q]!, "uz"));
  if (q === 0) lines.push(`  const e0 = W0 * (rho - 1 - rho * uu);`);
  else {
    lines.push(`  const cu${q} = ${cu};`);
    lines.push(`  const e${q} = ${wname(q)} * (rho - 1 + rho * (3 * cu${q} + 4.5 * cu${q} * cu${q} - uu));`);
  }
  lines.push(`  const n${q} = g${q} - e${q};`);
}
const pi = (a: readonly number[], b: readonly number[]): string => {
  let s = "";
  for (let q = 0; q < Q; q++) s += term(a[q]! * b[q]!, `n${q}`);
  return sum(s);
};
lines.push(`  const pxx = ${pi(CX, CX)};`);
lines.push(`  const pyy = ${pi(CY, CY)};`);
lines.push(`  const pzz = ${pi(CZ, CZ)};`);
lines.push(`  const pxy = ${pi(CX, CY)};`);
lines.push(`  const pxz = ${pi(CX, CZ)};`);
lines.push(`  const pyz = ${pi(CY, CZ)};`);
lines.push("  let tau = tau0;");
lines.push("  if (smag > 0) {");
lines.push("    const norm = Math.sqrt(pxx * pxx + pyy * pyy + pzz * pzz + 2 * (pxy * pxy + pxz * pxz + pyz * pyz));");
lines.push("    tau = 0.5 * (tau0 + Math.sqrt(tau0 * tau0 + (smag * norm) / rho));");
lines.push("  }");
lines.push("  const keep = 4.5 * (1 - 1 / tau);");
lines.push("  const tr = (pxx + pyy + pzz) / 3;");
for (let q = 0; q < Q; q++) {
  const cx = CX[q]!, cy = CY[q]!, cz = CZ[q]!;
  let s = term(cx * cx, "pxx") + term(cy * cy, "pyy") + term(cz * cz, "pzz") + term(2 * cx * cy, "pxy") + term(2 * cx * cz, "pxz") + term(2 * cy * cz, "pyz");
  s += " - tr";
  lines.push(`  next[${q === 0 ? "" : `${q} * n + `}c] = e${q} + keep * ${wname(q)} * (${sum(s)});`);
}
lines.push("  macro[0] = rho;");
lines.push("  macro[1] = ux;");
lines.push("  macro[2] = uy;");
lines.push("  macro[3] = uz;");
lines.push("}");
void W;
writeFileSync(new URL("../src/fast-step.ts", import.meta.url), lines.join("\n") + "\n");
